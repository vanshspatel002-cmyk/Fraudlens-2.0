-- Additive customer ownership and durable PDF artifacts. Historical cases are
-- intentionally unowned: matching an email never grants account ownership.
CREATE TABLE customer_accounts (
    customer_id TEXT PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    name TEXT NOT NULL,
    enabled BIGINT NOT NULL DEFAULT 1 CHECK(enabled IN (0,1)),
    created_at DOUBLE PRECISION NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE customer_sessions (
    token_hash TEXT PRIMARY KEY,
    customer_id TEXT NOT NULL REFERENCES customer_accounts(customer_id),
    credential_hash TEXT NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE INDEX idx_customer_sessions_expiry ON customer_sessions(expires_at);
CREATE TABLE case_owners (
    case_id TEXT PRIMARY KEY REFERENCES cases(case_id),
    customer_id TEXT NOT NULL REFERENCES customer_accounts(customer_id),
    created_at DOUBLE PRECISION NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE INDEX idx_case_owners_customer ON case_owners(customer_id,created_at);
CREATE TABLE report_artifacts (
    snapshot_id TEXT PRIMARY KEY REFERENCES report_snapshots(snapshot_id),
    renderer_version TEXT NOT NULL,
    pdf_base64 TEXT,
    sha256 TEXT,
    created_at DOUBLE PRECISION NOT NULL,
    error_type TEXT,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
