-- Private backend schema. The migration runner creates/selects it atomically.
-- TEXT timestamps and JSON deliberately preserve source bytes and API contracts.
-- DOUBLE PRECISION matches SQLite REAL; embeddings remain JSON, not pgvector.
-- rowid is an explicit causal sequence, preserved during SQLite import.
CREATE TABLE claimants (
    claimant_id TEXT PRIMARY KEY, name TEXT NOT NULL, phone TEXT NOT NULL,
    bank_account TEXT NOT NULL, address TEXT NOT NULL, created_at TEXT NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE cases (
    case_id TEXT PRIMARY KEY, claimant_id TEXT NOT NULL, garage_id TEXT NOT NULL,
    claim_type TEXT NOT NULL, declared_time TEXT, declared_location TEXT,
    latitude DOUBLE PRECISION, longitude DOUBLE PRECISION,
    agent_type TEXT NOT NULL DEFAULT 'claims', claim_amount DOUBLE PRECISION,
    vehicle_registration TEXT, status TEXT NOT NULL DEFAULT 'open', created_at TEXT NOT NULL,
    vehicle_make TEXT, vehicle_model TEXT, vehicle_variant TEXT, vehicle_year BIGINT,
    engine_number TEXT, chassis_number TEXT, rto TEXT, fuel_type TEXT, idv DOUBLE PRECISION,
    policy_number TEXT, policy_type TEXT, previous_policy_number TEXT, policy_ncb_percent DOUBLE PRECISION,
    policy_start_date TEXT, policy_end_date TEXT, person_name TEXT, person_dob TEXT,
    person_address TEXT, person_contact TEXT, driving_license_number TEXT, fir_number TEXT,
    settlement_preference TEXT, bank_account_last4 TEXT, declaration_notes TEXT,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
-- Cases historically accept an unregistered claimant identifier. Do not add a
-- claimant FK that would reject the preserved applicant intake contract.
CREATE TABLE findings (
    finding_id TEXT PRIMARY KEY, check_id TEXT NOT NULL,
    case_id TEXT NOT NULL REFERENCES cases(case_id), category TEXT NOT NULL,
    verdict TEXT NOT NULL, confidence DOUBLE PRECISION NOT NULL,
    explanation TEXT NOT NULL, evidence TEXT NOT NULL CHECK(jsonb_typeof(evidence::jsonb)='object'),
    created_at TEXT NOT NULL, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE perception_records (
    content_hash TEXT PRIMARY KEY, source TEXT NOT NULL, embedding TEXT,
    caption TEXT, ocr_text TEXT, damage_description TEXT, damage_severity TEXT,
    weather_observed TEXT, road_condition TEXT, shadow_direction TEXT, shadow_length TEXT,
    lighting TEXT, plate_text TEXT, scene_context TEXT, anomaly_notes TEXT,
    raw_response TEXT NOT NULL CHECK(jsonb_typeof(raw_response::jsonb)='object'),
    created_at TEXT NOT NULL, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE image_artifacts (
    artifact_id TEXT PRIMARY KEY, case_id TEXT NOT NULL REFERENCES cases(case_id),
    content_hash TEXT NOT NULL REFERENCES perception_records(content_hash),
    filename TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'unspecified', uploaded_at TEXT NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE agent_decisions (
    decision_id TEXT PRIMARY KEY, case_id TEXT NOT NULL REFERENCES cases(case_id),
    recommendation TEXT NOT NULL, confidence DOUBLE PRECISION NOT NULL, summary TEXT NOT NULL,
    supporting_finding_ids TEXT NOT NULL CHECK(jsonb_typeof(supporting_finding_ids::jsonb)='array'),
    requested_artifacts TEXT NOT NULL CHECK(jsonb_typeof(requested_artifacts::jsonb)='array'),
    policy_version TEXT NOT NULL DEFAULT 'unversioned', risk_band TEXT, score DOUBLE PRECISION,
    tool_calls_count BIGINT NOT NULL DEFAULT 0, iterations_count BIGINT NOT NULL DEFAULT 0,
    llm_calls_count BIGINT NOT NULL DEFAULT 0, latency_ms BIGINT NOT NULL DEFAULT 0, created_at TEXT NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    UNIQUE(decision_id, case_id)
);
CREATE TABLE images (
    image_id TEXT PRIMARY KEY, case_id TEXT NOT NULL REFERENCES cases(case_id),
    path TEXT NOT NULL, content_hash TEXT NOT NULL, phash TEXT NOT NULL, dhash TEXT NOT NULL,
    embedding TEXT CHECK(embedding IS NULL OR jsonb_typeof(embedding::jsonb) IN ('array','null')),
    exif TEXT NOT NULL CHECK(jsonb_typeof(exif::jsonb)='object'), created_at TEXT NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE audit_log (
    event_id TEXT PRIMARY KEY, event_type TEXT NOT NULL, case_id TEXT,
    details TEXT NOT NULL CHECK(jsonb_typeof(details::jsonb)='object'), created_at TEXT NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE admin_actions (
    case_id TEXT NOT NULL REFERENCES cases(case_id), admin_id TEXT NOT NULL,
    action TEXT NOT NULL, reason TEXT, timestamp TEXT NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);
CREATE TABLE cache_entries (
    namespace TEXT NOT NULL, cache_key TEXT NOT NULL,
    value TEXT NOT NULL CHECK(value::jsonb IS NOT NULL), created_at TEXT NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE, PRIMARY KEY(namespace,cache_key)
);
CREATE TABLE admin_sessions (
    token_hash TEXT PRIMARY KEY, actor TEXT NOT NULL, credential_hash TEXT NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE api_jobs (
    job_id TEXT PRIMARY KEY, case_id TEXT NOT NULL REFERENCES cases(case_id),
    updated_at DOUBLE PRECISION NOT NULL, payload TEXT NOT NULL,
    status TEXT NOT NULL CHECK(status IN ('queued','running','completed','failed','interrupted')),
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    CHECK(payload::jsonb ->> 'status'=status),
    CHECK(payload::jsonb ->> 'job_id'=job_id),
    CHECK(payload::jsonb ->> 'case_id'=case_id), UNIQUE(job_id,case_id)
);
CREATE TABLE organizations (
    organization_id TEXT PRIMARY KEY, name TEXT NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE reviewer_accounts (
    email TEXT PRIMARY KEY, password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('admin','reviewer','viewer')),
    organization_id TEXT NOT NULL DEFAULT 'local' REFERENCES organizations(organization_id),
    enabled BIGINT NOT NULL DEFAULT 1 CHECK(enabled IN (0,1)),
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE applicant_grants (
    token_hash TEXT PRIMARY KEY, case_id TEXT NOT NULL REFERENCES cases(case_id),
    expires_at DOUBLE PRECISION NOT NULL, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE evidence_requests (
    request_id TEXT PRIMARY KEY, case_id TEXT NOT NULL REFERENCES cases(case_id),
    artifacts TEXT NOT NULL CHECK(jsonb_typeof(artifacts::jsonb)='array'), actor TEXT NOT NULL,
    status TEXT NOT NULL, created_at DOUBLE PRECISION NOT NULL, fulfilled_at DOUBLE PRECISION,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE, UNIQUE(request_id,case_id)
);
CREATE TABLE evidence_batches (
    batch_id TEXT PRIMARY KEY, case_id TEXT NOT NULL REFERENCES cases(case_id),
    request_id TEXT, image_ids TEXT NOT NULL CHECK(jsonb_typeof(image_ids::jsonb)='array'),
    created_at DOUBLE PRECISION NOT NULL, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    FOREIGN KEY(request_id,case_id) REFERENCES evidence_requests(request_id,case_id)
);
CREATE TABLE submission_receipts (
    receipt_key TEXT PRIMARY KEY, fingerprint TEXT NOT NULL,
    response TEXT NOT NULL CHECK(jsonb_typeof(response::jsonb)='object'), created_at DOUBLE PRECISION NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE processing_results (
    run_id TEXT PRIMARY KEY, case_id TEXT NOT NULL REFERENCES cases(case_id), decision_id TEXT NOT NULL,
    finding_ids TEXT NOT NULL CHECK(jsonb_typeof(finding_ids::jsonb)='array'),
    image_ids TEXT NOT NULL CHECK(jsonb_typeof(image_ids::jsonb)='array'), policy_version TEXT NOT NULL,
    converged BIGINT NOT NULL CHECK(converged IN (0,1)), created_at DOUBLE PRECISION NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    FOREIGN KEY(run_id,case_id) REFERENCES api_jobs(job_id,case_id),
    FOREIGN KEY(decision_id,case_id) REFERENCES agent_decisions(decision_id,case_id)
);
CREATE TABLE report_snapshots (
    snapshot_id TEXT PRIMARY KEY, case_id TEXT NOT NULL REFERENCES cases(case_id), run_id TEXT,
    payload TEXT NOT NULL CHECK(jsonb_typeof(payload::jsonb)='object'), created_at DOUBLE PRECISION NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    FOREIGN KEY(run_id,case_id) REFERENCES api_jobs(job_id,case_id)
);
CREATE INDEX idx_claimants_phone ON claimants(phone);
CREATE INDEX idx_claimants_bank_account ON claimants(bank_account);
CREATE INDEX idx_cases_garage ON cases(garage_id);
CREATE INDEX idx_cases_vehicle_registration ON cases(vehicle_registration);
CREATE INDEX idx_cases_policy_number ON cases(policy_number);
CREATE INDEX idx_findings_case ON findings(case_id);
CREATE INDEX idx_artifacts_case ON image_artifacts(case_id);
CREATE INDEX idx_artifacts_hash ON image_artifacts(content_hash);
CREATE INDEX idx_decisions_case ON agent_decisions(case_id);
CREATE INDEX idx_decisions_policy ON agent_decisions(policy_version);
CREATE INDEX idx_images_case ON images(case_id);
CREATE INDEX idx_images_content_hash ON images(content_hash);
CREATE INDEX idx_audit_case ON audit_log(case_id);
CREATE INDEX idx_admin_actions_case ON admin_actions(case_id);
CREATE INDEX idx_api_jobs_case ON api_jobs(case_id,updated_at);
CREATE UNIQUE INDEX idx_one_active_job ON api_jobs(case_id) WHERE status IN ('queued','running');
CREATE INDEX idx_api_jobs_queue ON api_jobs(rowid) WHERE status='queued';
CREATE INDEX idx_sessions_expiry ON admin_sessions(expires_at);
CREATE INDEX idx_requests_case ON evidence_requests(case_id,created_at);
CREATE INDEX idx_reports_case ON report_snapshots(case_id,rowid);
CREATE INDEX idx_results_case ON processing_results(case_id);

-- Immutable history at the database boundary as well as in application code.
CREATE FUNCTION refuse_report_mutation() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog AS $$
BEGIN
    RAISE EXCEPTION 'Report history is immutable';
END;
$$;
CREATE TRIGGER immutable_report BEFORE UPDATE OR DELETE ON report_snapshots
FOR EACH ROW EXECUTE FUNCTION refuse_report_mutation();
