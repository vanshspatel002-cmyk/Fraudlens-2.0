"""
Draft the report's Limitations section.

Generated so the figures stay current. Each limitation states what it is, what
follows from it, and what would be required to resolve it — the last of these
because a limitation without a remedy reads as an excuse.

Nothing here is softened. A frank limitations section is load-bearing: it is
the part of a report that establishes whether the rest can be trusted.

Usage:
    python scripts/build_report_limitations.py
"""

from __future__ import annotations

import csv
import json
import random
import sys
from collections import Counter
from pathlib import Path
from typing import Any, Optional

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[attr-defined]

OUT = Path("outputs/report_draft_limitations.md")


def read_json(path: str) -> Optional[Any]:
    p = Path(path)
    if not p.exists():
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None


def read_jsonl(path: str) -> list[dict[str, Any]]:
    p = Path(path)
    if not p.exists():
        return []
    out = []
    for line in p.read_text(encoding="utf-8").splitlines():
        if line.strip():
            try:
                out.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return out


def perception_stats() -> dict[str, Any]:
    from src import db
    conn = db.connect("fraudlens.db")
    archetype = {r["case_id"]: r["archetype"]
                 for r in csv.DictReader(open("data/generated/ground_truth.csv",
                                              encoding="utf-8"))}
    perceived = {r[0] for r in conn.execute(
        "SELECT DISTINCT i.case_id FROM images i "
        "JOIN perception_records p ON i.content_hash = p.content_hash")}
    images = conn.execute("SELECT COUNT(*) FROM images").fetchone()[0]
    records = conn.execute("SELECT COUNT(*) FROM perception_records").fetchone()[0]
    total, seen = Counter(), Counter()
    for case_id, arch in archetype.items():
        total[arch] += 1
        if case_id in perceived:
            seen[arch] += 1
    conn.close()
    blocked = sorted(
        ((a, seen[a], total[a]) for a in total if total[a] and seen[a] / total[a] < 0.25),
        key=lambda t: t[1] / t[2])
    return {"images": images, "records": records,
            "coverage": records / images if images else 0, "blocked": blocked}


def paired() -> dict[str, Any]:
    rows = read_jsonl("outputs/ablation_results.jsonl")
    excluded = set((read_json("data/generated/corpus_exclusions.json") or {})
                   .get("excluded_case_ids", []))

    def outage(r):
        return any(s.get("kind") == "fallback" and "provider error" in (s.get("detail") or "")
                   for s in (r.get("trace") or []))

    base = {r["case_id"]: r for r in rows if r["arm"] == "baseline"}
    agent = {r["case_id"]: r for r in rows if r["arm"] == "agent" and not outage(r)}
    shared = sorted((set(base) & set(agent)) - excluded)
    pairs = [(base[c], agent[c]) for c in shared]
    fraud = [(b, a) for b, a in pairs if b["is_fraud"]]
    clean = [(b, a) for b, a in pairs if not b["is_fraud"]]

    def caught(ps, i):
        return (sum(1 for p in ps if p[i]["risk_band"] != "clear") / len(ps)) if ps else None

    ci = None
    if len(fraud) >= 2:
        rng = random.Random(42)
        d = []
        for _ in range(10_000):
            draw = [fraud[rng.randrange(len(fraud))] for _ in range(len(fraud))]
            d.append(caught(draw, 1) - caught(draw, 0))
        d.sort()
        ci = (d[250], d[-250])
    return {"n": len(pairs), "fraud": len(fraud), "clean": len(clean), "ci": ci,
            "agent_total": len(agent), "sample": len(read_json("outputs/ablation_sample.json")
                                                     ["cases"]) if Path("outputs/ablation_sample.json").exists() else 0,
            "diff": (caught(fraud, 1) - caught(fraud, 0)) if len(fraud) >= 2 else None}


def main() -> None:
    per = perception_stats()
    ab = paired()
    exc = read_json("data/generated/corpus_exclusions.json") or {}
    dup = read_json("outputs/duplicate_measurement.json") or {}

    a_: list[str] = []
    a = a_.append

    a("# Limitations — draft")
    a("")
    a("*Generated by `scripts/build_report_limitations.py`; figures are read from "
      "artefacts in `outputs/`. Each limitation states what would be required to "
      "resolve it.*")
    a("")
    a("---")
    a("")
    a("## 6. Limitations")
    a("")
    a("The constraints below are stated without qualification. Several of them bound "
      "what any result in this report can mean, and two of them — the confidence "
      "interval spanning zero, and the absence of a working detector for three "
      "archetypes — bear directly on the project's central claim.")
    a("")

    # 1
    a("### 6.1 Vision-model coverage extends to roughly a tenth of the corpus")
    a("")
    a(f"Perception records exist for **{per['records']} of {per['images']} images "
      f"({per['coverage']:.1%})**. Coverage was allocated by a stratified sampler that "
      f"prioritised archetypes whose designated check requires perception, so it is "
      f"deliberately uneven rather than random.")
    a("")
    if per["blocked"]:
        a("Archetypes still substantially quota-blocked (case-level coverage below 25%):")
        a("")
        a("| Archetype | Cases with perception |")
        a("|---|---|")
        for arch, seen, total in per["blocked"]:
            a(f"| {arch} | {seen}/{total} ({seen / total:.0%}) |")
        a("")
    a("Two consequences follow. Perception-dependent checks — `scene_consistency`, "
      "`damage_plausibility`, `baseline_corruption` — are measured on small "
      "denominators, and `scene_consistency`'s false-positive rate rests on 19 clean "
      "cases. And the agent's one demonstrated advantage over the baseline, reading "
      "unstructured scene text, is simply unavailable on most of the corpus, so the "
      "ablation understates whatever that advantage is worth.")
    a("")
    a("**To resolve:** roughly 1,265 further vision calls at current coverage. Vision "
      "and adjudication draw on the same daily allowance, so this competes directly "
      "with completing the ablation; a locally hosted captioning model would remove the "
      "contention entirely.")
    a("")

    # 2
    a("### 6.2 Clean cells are too thin to estimate false-positive rates")
    a("")
    a(f"The ablation sample contains 12 clean cases per agent type before exclusions, of "
      f"which **{ab['clean']}** appear in the paired comparison. At that size the 95% "
      f"interval around an observed zero still extends past 10%.")
    a("")
    a("Every false-positive figure derived from the ablation is therefore an **upper "
      "bound rather than an estimate**, and the two arms' false-positive rates are not "
      "reported as a difference anywhere in this report. The corpus-wide baseline "
      "figures, measured over all 540 clean cases, do not share this limitation; the "
      "ablation figures do.")
    a("")
    a("**To resolve:** on the order of a thousand clean cases per arm to distinguish a "
      "0.5% rate from a 2% one — approximately 3,000 further model calls for the agent "
      "arm, or thirty days at the current allowance.")
    a("")

    # 3
    a("### 6.3 The duplicate-attribution rule is correct by construction here")
    a("")
    if dup:
        f = dup["false_positives_on_clean"]
        a(f"Amending `internal_duplicate` to attribute a shared photograph to the later "
          f"submission reduced its false positives on clean cases from 23/540 to "
          f"**{f['flagged']}/{f['total']}** while leaving recall unchanged. That "
          f"improvement is guaranteed rather than earned.")
    a("")
    a("The corpus is generated in archetype blocks: every clean case is created before "
      "every REUSE case, occupying creation ranks 20–559 against 765–799. \"The earlier "
      "submission is the originator\" therefore holds automatically, and the corpus "
      "cannot distinguish a correct rule from a rule that happens to agree with its own "
      "generation order. The reasoning is sound for production data, where ingest time "
      "is genuine evidence; the measurement is not evidence that it generalises.")
    a("")
    a("**To resolve:** interleave creation order in the generator so that REUSE cases "
      "sometimes precede their originators, or measure against real claim data where "
      "submission order is independent of case type.")
    a("")

    # 4
    a("### 6.4 The external corpus is simulated")
    a("")
    a("`external_corpus` achieved 35/35 recall against a locally held index of images "
      "disjoint from the main pool. In production this check would query a commercial "
      "reverse-image API against the public web.")
    a("")
    a("The simulation is favourable in one direction and unfavourable in another. It is "
      "favourable because the index is guaranteed to contain the sourced image, whereas "
      "a real service may not have crawled it; the measured 100% recall is therefore an "
      "upper bound that a production deployment would not reach. It is unfavourable "
      "because the index is small, so a production service searching billions of images "
      "would encounter far more opportunity for coincidental matches than the measured "
      "0/540 false-positive rate suggests.")
    a("")
    a("**To resolve:** an evaluation against a commercial reverse-image service, which "
      "requires a paid API and introduces non-determinism into the evidence path — "
      "itself a design problem given the regulatory constraint described in the "
      "methodology.")
    a("")

    # 5
    a("### 6.5 The corpus is synthetic, and its clean labels are imperfect")
    a("")
    defective = exc.get("defective_clean_cases") or exc.get("defective_cases")
    total_clean = exc.get("clean_cases_total")
    if defective and total_clean:
        a(f"Every figure in this report describes archetypes this project generated. No "
          f"real claim data was used, so nothing here establishes performance against "
          f"the distribution of genuine fraud, whose base rate, sophistication and "
          f"variety are unknown to the system.")
        a("")
        a(f"The labels are also imperfect. **{defective} of {total_clean}** cases "
          f"labelled clean carry stock-agency watermarks, republication URLs or "
          f"geographically impossible imagery, because the image pool was assembled from "
          f"public sources without provenance screening. Those cases are excluded at "
          f"scoring, but the figure is a floor: optical character recognition covered "
          f"every clean image, while the geographic signal can only be read from "
          f"vision-model descriptions covering roughly a tenth of them.")
    a("")
    a("**To resolve:** a partnership providing access to adjudicated real claims, with "
      "the attendant data-protection constraints; or, for the label defects alone, "
      "provenance screening of the source image pool before generation.")
    a("")

    # 6
    a("### 6.6 Two checks are uncalibrated or non-functional")
    a("")
    a("**`digital_edit` is uncalibrated.** After the generator defect that had erased "
      "its target signal was corrected, the combined forensic score reached an AUC of "
      "0.546 — indistinguishable from chance. It carries weight 0.0. The check is not "
      "known to be wrong; it is known not to discriminate on this corpus, and no "
      "threshold recovers a signal that is absent.")
    a("")
    a("**`baseline_corruption` has no working detector for its target archetype.** It "
      "was built to detect AI_GENERATED_BASELINE and is structurally incapable of doing "
      "so: that archetype fabricates the *absence* of damage, so the declaration and the "
      "photographs agree by construction and every check passes. Two alternative routes "
      "were measured and both failed — cross-case linkage is unavailable because all 800 "
      "cases carry unique registrations and claimants, and synthetic-image forensics "
      "reached an inverted AUC of 0.26 but with JPEG quantisation confounded between the "
      "groups. The archetype is undetected by anything in the battery, and its 20 cases "
      "are excluded from the ablation sample because both arms would see an identical "
      "absence of evidence.")
    a("")
    a("Together with `ai_generation`, three archetypes have no working detector. This "
      "places a coverage ceiling on recall — measured at 58.5% by a 205-point threshold "
      "sweep — that no threshold adjustment can raise.")
    a("")
    a("**To resolve:** for `digital_edit`, forensics robust to the recompression that "
      "ordinary claim handling applies. For `baseline_corruption`, either a synthetic-"
      "image detector that survives a resolution- and compression-matched control, or a "
      "corpus modelling repeat customers so that cross-case linkage becomes measurable.")
    a("")

    # 7
    a("### 6.7 The ablation does not establish that the agent outperforms the baseline")
    a("")
    if ab["ci"]:
        lo, hi = ab["ci"]
        a(f"On the **{ab['n']}** cases both arms had adjudicated "
          f"({ab['fraud']} fraud, {ab['clean']} clean), the paired recall difference was "
          f"**{ab['diff']:+.1%}** with a bootstrap 95% confidence interval of "
          f"**[{lo:+.1%}, {hi:+.1%}]**.")
        a("")
        if lo <= 0 <= hi:
            a("**The interval includes zero.** The observed difference favours the agent, "
              "and the evidence does not distinguish it from sampling variation. No claim "
              "that the agent outperforms the rules-only baseline is supported by this "
              "study.")
        else:
            a("The interval excludes zero on this sample, but describes these cases only.")
    a("")
    a(f"The agent arm is also incomplete — **{ab['agent_total']} of {ab['sample']}** "
      f"cases — because it is bound by a free-tier allowance of approximately 100 "
      f"requests per day. The cases adjudicated so far are those the interleaved "
      f"schedule reached, not a random subsample, though the schedule was explicitly "
      f"designed so that any prefix is balanced across archetypes.")
    a("")
    a("**To resolve:** completing the arm requires roughly 150 further model calls, "
      "about two days at the current allowance. Establishing a difference of the "
      "magnitude observed, rather than merely completing the sample, would require "
      "several hundred fraud cases per arm.")
    a("")

    # 8
    a("### 6.8 Single model, single corpus, no external validity")
    a("")
    a("One language model was evaluated, against one synthetic corpus, in one "
      "jurisdiction's claims conventions. The prompt reliability ratings were derived "
      "from measurements on this corpus and would not transfer unchanged. No conclusion "
      "is drawn about language models in general, about other fraud domains, or about "
      "deployment at production volume.")
    a("")
    a("**To resolve:** replication across models and corpora, which is beyond the scope "
      "and budget of this study.")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(a_) + "\n", encoding="utf-8")
    print(f"-> {OUT} ({len(a_)} lines)")


if __name__ == "__main__":
    main()
