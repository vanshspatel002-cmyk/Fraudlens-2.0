"""
Draft the report's Methodology section.

Generated rather than hand-written, for the same reason as the results draft:
corpus counts and measured costs change, and a typed number goes stale
silently. Every figure is read from an artefact and the artefact is cited.

Register: past tense, third person, academic.

Usage:
    python scripts/build_report_methodology.py
"""

from __future__ import annotations

import csv
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any, Optional

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[attr-defined]

OUT = Path("outputs/report_draft_methodology.md")


def read_json(path: str) -> Optional[Any]:
    p = Path(path)
    if not p.exists():
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None


def read_jsonl(path: str) -> list[dict[str, Any]]:
    p = Path(path)
    if not p.exists():
        return []
    out = []
    for line in p.read_text(encoding="utf-8").splitlines():
        if line.strip():
            try:
                out.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return out


def corpus_counts() -> dict[str, Any]:
    path = Path("data/generated/ground_truth.csv")
    if not path.exists():
        return {}
    with open(path, encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    return {"total": len(rows), "by_archetype": Counter(r["archetype"] for r in rows)}


def agent_cost() -> dict[str, Any]:
    rows = [r for r in read_jsonl("outputs/ablation_results.jsonl") if r["arm"] == "agent"]
    if not rows:
        return {}
    return {
        "n": len(rows),
        "calls": sum(r["llm_calls"] for r in rows) / len(rows),
        "tools": sum(r["tool_calls"] for r in rows) / len(rows),
        "latency": sum(r["latency_ms"] for r in rows) / len(rows) / 1000,
    }


def main() -> None:
    corpus = corpus_counts()
    cost = agent_cost()
    checks = read_json("outputs/check_performance_v2.md") is not None

    a_: list[str] = []
    a = a_.append

    a("# Methodology — draft")
    a("")
    a("*Generated by `scripts/build_report_methodology.py`. Counts and measured costs "
      "are read from artefacts in `outputs/` and `data/generated/`; re-run to refresh.*")
    a("")
    a("---")
    a("")
    a("## 3. Methodology")
    a("")

    # ---------------------------------------------------------------
    a("### 3.1 A hybrid architecture, and why the split falls where it does")
    a("")
    a("The system separated evidence gathering from adjudication. Evidence gathering was "
      "deterministic: a fixed battery of checks examined each case and emitted structured "
      "findings. Adjudication — deciding what those findings warranted — was delegated to "
      "a language model.")
    a("")
    a("The division was driven by a regulatory constraint rather than an engineering "
      "preference. Insurance regulation requires that materially identical cases receive "
      "materially identical treatment, and a claimant is entitled to an explanation of an "
      "adverse decision that refers to evidence rather than to a model's disposition. A "
      "non-deterministic component in the evidence path would violate the first "
      "requirement: the same photograph could yield a duplicate match on one execution "
      "and not on another, and no audit could reconstruct which had occurred. Every "
      "check was therefore implemented as a deterministic function of stored data, so "
      "that re-running the battery over an unchanged case reproduces its findings "
      "exactly.")
    a("")
    a("Judgement was treated differently. Deciding whether two moderate concerns and one "
      "inconclusive result warrant a desk review is not a computation with a correct "
      "answer; it is the exercise of discretion that a human adjuster performs, and the "
      "system's purpose was to test whether a language model could perform it "
      "defensibly. Placing the model there — and only there — meant that variation in "
      "its output could never alter what evidence existed, only what was concluded from "
      "it.")
    a("")
    a("The design also constrained the action space. The system emits four "
      "recommendations — clear, request further evidence, route to desk review, or "
      "escalate to a special investigation unit — and has no representation for "
      "rejection. This was enforced structurally rather than by instruction: the "
      "`Recommendation` enumeration contains no rejecting member, so no prompt, parse "
      "failure or adversarial input can produce one. The adjudication engine "
      "additionally scans generated narratives for rejection language and coerces any "
      "such output to escalation while recording an audit event.")
    a("")

    # ---------------------------------------------------------------
    a("### 3.2 The perception and reasoning split")
    a("")
    a("Two distinct uses of the language model were separated. A vision model described "
      "each image once, producing a structured perception record — scene context, damage "
      "severity, weather, shadow direction, lighting, any legible registration plate — "
      "which was persisted against the image's SHA-256 content hash. Checks then read "
      "those records rather than calling the vision model themselves.")
    a("")
    a("Content-hash keying had a practical consequence beyond deduplication: perception "
      "records survive regeneration of the corpus, so an image whose bytes are unchanged "
      "need never be described twice even when the case containing it is rebuilt.")
    a("")
    if cost:
        a(f"The rationale was cost. The study ran against a free API tier permitting "
          f"approximately 100 requests per key per day, and vision and reasoning calls "
          f"drew on the same allowance. Describing an image once and reading the record "
          f"many times converted a per-check cost into a per-image cost. Adjudication "
          f"was measured at **{cost['calls']:.1f} model calls, {cost['tools']:.1f} tool "
          f"invocations and {cost['latency']:.1f} seconds per case** across "
          f"{cost['n']} agent adjudications (`outputs/ablation_results.jsonl`), which "
          f"placed a full pass over the corpus beyond a single day's allowance and "
          f"dictated the sampling design described in §3.6.")
        a("")

    # ---------------------------------------------------------------
    a("### 3.3 Corpus construction")
    a("")
    if corpus:
        total = corpus["total"]
        by = corpus["by_archetype"]
        clean = by.get("CLEAN", 0)
        a(f"A synthetic corpus of **{total}** cases was constructed, comprising "
          f"**{clean}** labelled-clean cases and **{total - clean}** fraud cases across "
          f"**{len(by) - 1}** archetypes. Ground truth is known by construction: each "
          f"fraudulent case was generated by applying a specified manipulation to a "
          f"known-clean base, and the manipulation applied is recorded alongside the "
          f"case.")
        a("")
        a("| Archetype | Cases | Manipulation applied |")
        a("|---|---|---|")
        described = {
            "CLEAN": "none — an honest claim",
            "REUSE": "a photograph from an earlier case resubmitted as new evidence",
            "EXTERNAL_SOURCING": "an image drawn from an external corpus rather than "
                                 "photographed at the scene",
            "METADATA_FORGERY": "EXIF timestamps and device fields rewritten to match "
                                "the declared incident",
            "THRESHOLD_GAMING": "a claim amount placed just below the survey "
                                "authorisation threshold, at a garage exhibiting that "
                                "billing pattern",
            "CONTEXT_MISMATCH": "a declaration whose stated time, location or weather "
                                "contradicts what the photographs show",
            "DIGITAL_EDIT": "damage composited into an otherwise undamaged vehicle",
            "AI_GENERATED": "a synthetic image of a damaged vehicle",
            "AI_GENERATED_BASELINE": "a synthetic image of an *undamaged* vehicle "
                                     "submitted at policy inception, fabricating the "
                                     "absence of pre-existing damage",
        }
        for arch, n in sorted(by.items(), key=lambda kv: (kv[0] != "CLEAN", kv[0])):
            a(f"| {arch} | {n} | {described.get(arch, '—')} |")
        a("")
        a("Cases were assigned to one of two workflows. Claims cases concern an incident "
          "and a monetary amount; underwriting cases are pre-policy inspections with no "
          "incident and no claim amount, where the fraud of interest inverts — an "
          "applicant conceals damage that already exists rather than fabricating damage "
          "that does not.")
        a("")

    # ---------------------------------------------------------------
    a("### 3.4 Disjointness and near-duplicate guarantees")
    a("")
    a("Two properties were enforced during generation and verified afterwards.")
    a("")
    a("**Disjointness of the external corpus.** The images used to construct "
      "EXTERNAL_SOURCING cases were held in a pool disjoint from the images used for all "
      "other cases, so that a match against the external index could only arise from the "
      "intended manipulation and never from an accidental overlap.")
    a("")
    a("**Absence of unintended near-duplicates.** Perceptual hashes and CLIP embeddings "
      "were computed for every image, and clean cases were checked for near-duplicate "
      "collisions so that `internal_duplicate` could not fire on two honest claims that "
      "happened to photograph similar vehicles.")
    a("")
    a("What these guarantees do **not** ensure is more important to state. They ensure "
      "that a duplicate match is not an accident; they do not ensure that the case "
      "flagged is the case at fault — an omission that produced a measurable "
      "misattribution error discussed in the results. Nor do they ensure that the "
      "labelled-clean cases are visually clean: an audit found "
      + (f"{(read_json('data/generated/corpus_exclusions.json') or {}).get('defective_clean_cases', 'a number of')} "
         "of them carrying stock-agency watermarks or geographically impossible imagery, "
         "because the underlying image pool was assembled from public sources without "
         "provenance screening.")
      )
    a("")

    # ---------------------------------------------------------------
    a("### 3.5 The check battery and the Finding contract")
    a("")
    a("Each check implemented a single interface and returned zero or more findings. A "
      "finding carried the check's identifier, one of five categories (identity, "
      "history, provenance, context, economic), a verdict, a confidence in [0, 1], a "
      "human-readable explanation, and a structured evidence dictionary.")
    a("")
    a("Verdicts were three-valued: PASS, CONCERN, and INCONCLUSIVE. The third was "
      "load-bearing rather than a convenience. Most photographs in the corpus are close "
      "crops carrying no sky, no shadow and no metadata, so \"the check could not "
      "determine this\" is the ordinary outcome for an honest claim. Collapsing it into "
      "either PASS or CONCERN would have been an error in opposite directions, and "
      "treating an accumulation of inconclusive results as cumulative suspicion is the "
      "most direct route to manufacturing a false accusation. INCONCLUSIVE therefore "
      "contributed exactly zero to the risk score, and the adjudication prompt stated "
      "this explicitly.")
    a("")
    a("Each check additionally declared a target archetype and a weight. The target "
      "archetype fixed the denominator against which its recall was reported: recall was "
      "never pooled across the corpus, since a check designed to detect image reuse "
      "should not be penalised for failing to detect metadata forgery. Weights were "
      "derived from measurement rather than assigned by intuition, and a check measured "
      "to have no discriminative power was assigned weight 0.0 while continuing to run "
      "and record its outputs.")
    a("")
    a("Checks were required to degrade rather than fail. An exception inside a check was "
      "caught and converted to an INCONCLUSIVE finding, so a defect in one check could "
      "not deprive an adjudicator of the others' evidence.")
    a("")

    # ---------------------------------------------------------------
    a("### 3.6 Two policies, one engine")
    a("")
    a("Claims and underwriting adjudication shared a single reasoning engine and differed "
      "only in policy: the system prompt, the set of checks executed, the tools "
      "available, and the bias applied under ambiguity. The claims policy preferred "
      "escalation when evidence was ambiguous; the underwriting policy preferred "
      "requesting a further photograph, on the grounds that a pre-policy inspection has "
      "no deadline pressure and no incident to reconstruct.")
    a("")
    a("The engine executed a bounded loop. At each iteration the model received the case "
      "description and the findings, and could either call one of the policy's tools or "
      "return a decision. Four tools were provided: widening the image-similarity "
      "threshold, retrieving claimant history, retrieving garage history, and re-reading "
      "the perception record for an image. Tool calls outside the policy's permitted set "
      "were refused and reported back to the model rather than executed. Iteration and "
      "tool-call caps bounded cost, an unparseable reply was retried once, and any "
      "failure to converge produced a documented fallback to desk review rather than an "
      "exception.")
    a("")
    a("Findings were passed to the model in a reduced form. The raw evidence dictionary "
      "was withheld — it contains embeddings and file paths of no use to a language "
      "model — while the finding identifier was retained, so that the model could cite "
      "specific findings and those citations could be validated against the findings "
      "actually supplied. Citations of identifiers that had not been supplied were "
      "discarded.")
    a("")
    a("Every step was recorded as an ordered trace: the tool invoked, its arguments, the "
      "keys of what it returned, and the latency of each call. The trace was persisted "
      "with the decision, so that the reasoning and the outcome could not diverge.")
    a("")

    # ---------------------------------------------------------------
    a("### 3.7 Ablation design")
    a("")
    a("The central experiment compared the agent against a rules-only baseline: a "
      "weighted sum over concern findings, where each finding contributed its check's "
      "weight multiplied by its confidence, with the total mapped to a risk band by "
      "thresholds selected via a 205-point sweep.")
    a("")
    a("The two arms were held identical in every respect but adjudication. The check "
      "battery was executed once per case and its findings passed to both arms, so a "
      "difference in outcome could not arise from the checks having behaved differently. "
      "The case sample was frozen to disk before either arm ran, because the corpus "
      "audit was still producing exclusions and re-deriving the sample per arm would "
      "have silently given the two arms different cases. Exclusions discovered "
      "afterwards were applied at scoring rather than at sampling.")
    a("")
    a("**Arms were reported separately by agent type.** Claims and underwriting invoke "
      "different prompts, different checks and different tools, and — more importantly — "
      "the underwriting workflow's only fraud archetype has no working detector. Pooling "
      "the two would average a discriminating configuration with a non-discriminating "
      "one and produce a figure describing neither.")
    a("")
    a("Cases on which the adjudicator never received a completed model response were "
      "excluded from scoring. Such a case records a provider outage rather than a "
      "judgement: it takes the documented desk-review fallback, and on a clean case that "
      "band would otherwise be counted as a false positive the agent never committed. "
      "Cases that failed to converge for reasons internal to the agent — reaching the "
      "iteration cap, or never producing a parseable decision — were retained, since "
      "that is the agent's own behaviour.")
    a("")
    a("Because the agent arm was quota-bound and incomplete at the time of analysis, the "
      "arms were compared only on cases both had adjudicated, using paired resampling "
      "for confidence intervals. Comparing a partial agent arm against a complete "
      "baseline would have measured which cases happened to be sampled.")
    a("")

    # ---------------------------------------------------------------
    a("### 3.8 Corpus falsifiability as a methodological finding")
    a("")
    a("The most consequential methodological observation of this work concerns the "
      "corpus rather than the system. Three archetypes were initially **unfalsifiable by "
      "construction**: no detector could have succeeded on them, because the generator "
      "had not produced the signal the detector sought.")
    a("")
    a("**DIGITAL_EDIT** composited damage into a clean vehicle and then recompressed the "
      "entire resulting image at uniform quality. JPEG-ghost analysis detects a region "
      "whose compression history differs from its surroundings; a global recompression "
      "pass erases precisely that discontinuity. The check was measuring an artefact the "
      "generator had removed. After the generator was amended to save once and to "
      "pre-compress the composited patch in half the cases, the ghost statistic's "
      "discrimination moved from inverted (AUC 0.331) to slightly better than chance "
      "(0.544).")
    a("")
    a("**CONTEXT_MISMATCH** altered a case's declared time, location or weather without "
      "regard to what its photographs actually showed. A declaration claiming rain was "
      "therefore no more likely to be paired with a visibly dry photograph than with a "
      "wet one, and the contradiction the check existed to find was present only by "
      "chance. The generator was inverted to select photographs by their visible "
      "conditions first and construct a contradicting declaration around them.")
    a("")
    a("**AI_GENERATED** cases were generated with no images at all. Recall against that "
      "archetype was not low; it was undefined, and reporting it as 0% would have "
      "attributed to the detector a failure that belonged to the corpus.")
    a("")
    a("The pattern this established governed the remainder of the work. Measured recall "
      "improved across successive sessions — 57.1%, 57.9%, 59.6%, 61.2% — and **every "
      "one of those gains followed a correction to the corpus; none followed the "
      "addition of a check**. Four checks were added over the same period and "
      "contributed nothing to recall, two of them being subsequently retired or assigned "
      "zero weight after measurement. A fifth round reduced measured recall to 58.5% by "
      "removing credit the battery had been accruing through a corpus artefact.")
    a("")
    a("The binding constraint on measured performance was therefore corpus construction "
      "rather than detection logic. The practical consequence is that a synthetic "
      "benchmark must be treated as an object of investigation in its own right: a check "
      "that scores zero is evidence about the check *or* about the data, and "
      "distinguishing the two requires deliberately attempting to falsify the data "
      "first. Every archetype in this corpus was subsequently subjected to that test, "
      "and the checks that survived it are the ones whose measurements are reported.")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(a_) + "\n", encoding="utf-8")
    print(f"-> {OUT} ({len(a_)} lines)")


if __name__ == "__main__":
    main()
